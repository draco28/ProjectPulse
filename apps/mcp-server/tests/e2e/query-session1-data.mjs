/**
 * Query Session 1 data from database
 */

import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient({
  datasources: {
    db: {
      url: 'postgresql://postgres:postgres123@192.168.1.15:5432/projectpulse_dev'
    }
  }
});

async function main() {
  const session = await prisma.onboardingSession.findUnique({
    where: {
      projectId_sessionNumber: {
        projectId: 3,
        sessionNumber: 1
      }
    },
    include: {
      project: {
        select: { name: true }
      }
    }
  });

  if (!session) {
    console.log('❌ No Session 1 data found for project 3');
    return;
  }

  const response = session.response;
  const planningAnswers = response.planningAnswers || {};

  console.log('='.repeat(80));
  console.log('SESSION 1 DATABASE STORED DATA');
  console.log('='.repeat(80));
  console.log('');
  console.log('Project:', session.project.name);
  console.log('Status:', session.status);
  console.log('Started:', session.startedAt?.toISOString());
  console.log('Completed:', session.completedAt?.toISOString());
  console.log('');

  console.log('=== PLANNING ANSWERS (10 PHASES) ===');
  console.log('');

  for (let i = 1; i <= 10; i++) {
    const phaseKey = `phase${i}`;
    const phaseAnswers = planningAnswers[phaseKey];

    if (phaseAnswers) {
      console.log(`Phase ${i}: ${Object.keys(phaseAnswers).length} questions answered`);
      Object.entries(phaseAnswers).forEach(([qId, answer]) => {
        console.log(`  ${qId}: ${String(answer).substring(0, 100)}...`);
      });
      console.log('');
    }
  }

  console.log('=== EXECUTIVE SUMMARY ===');
  console.log('');
  console.log('Word Count:', response.wordCount || 0);
  console.log('Generated At:', response.executiveSummaryGeneratedAt || 'N/A');
  console.log('Generated By:', response.generatedBy || 'N/A');
  console.log('');
  console.log('Summary (first 800 chars):');
  console.log('-'.repeat(80));
  const summary = response.executiveSummary || 'Not generated';
  console.log(summary.substring(0, 800) + '...');
  console.log('-'.repeat(80));

  await prisma.$disconnect();
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
